<h1>使用說明</h1>

<h2>它做什麼</h2>
<p>Pathie 常駐在系統匣。當你複製一個有效的檔案或資料夾路徑，或是 http(s) 網址，它會自動幫你開啟。</p>

<h2>系統匣操作</h2>
<p><b>左鍵點一下圖示</b>：暫停／恢復監控（圖示會變灰）。<br /><b>右鍵圖示</b>：暫停／恢復、開啟設定、退出。</p>

<h2>開啟規則</h2>
<p>資料夾一律直接開啟；檔案預設只在檔案總管中選取，不會執行。這些都能在「檔案與網址」調整。</p>

<h2>安全規則</h2>
<p>
  只有絕對路徑才會觸發，裸檔名與相對路徑會被忽略。網路路徑（\\host\share）預設不處理。每分鐘開啟次數超過上限會自動暫停監控。詳見「安全」。
</p>

<h2>找不到設定？</h2>
<p>關掉這個視窗不會結束 Pathie，它仍在系統匣。要再開啟，右鍵系統匣圖示選「設定…」。</p>
